/**
 * Generate src/api/schema.d.ts from the running backend's OpenAPI schema (ADR-008).
 * The backend URL comes from VITE_API_BASE_URL (frontend/.env or the environment).
 *
 *   npm run gen:api
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'
import { loadEnv } from 'vite'

const frontendDir = fileURLToPath(new URL('..', import.meta.url))
const outputFile = fileURLToPath(new URL('../src/api/schema.d.ts', import.meta.url))

const env = loadEnv('development', frontendDir, 'VITE_')
const baseUrl = env.VITE_API_BASE_URL?.replace(/\/+$/, '')
if (!baseUrl) {
  console.error('VITE_API_BASE_URL is not set (see frontend/.env.example)')
  process.exit(1)
}

const schemaUrl = new URL(`${baseUrl}/openapi.json`)
console.log(`Reading ${schemaUrl.href}`)

try {
  const ast = await openapiTS(schemaUrl)
  const banner =
    '/**\n * GENERATED by `npm run gen:api` from the backend OpenAPI schema. Do not edit by hand.\n */\n\n'
  writeFileSync(outputFile, banner + astToString(ast))
  console.log(`Wrote ${outputFile}`)
} catch (error) {
  console.error(`Could not generate API types from ${schemaUrl.href}. Is the backend running?`)
  console.error(error)
  process.exit(1)
}
